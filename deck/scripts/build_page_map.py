#!/usr/bin/env python3
"""
build_page_map.py — Phase 2 mapping: legacy 51 HTML files -> 33 logical slides.

Groups consecutive slide_NN.html files where file N is a progressive-disclosure
subslide of file N-1 (same slide, more blocks revealed => visible text superset).
Emits deck/data/pageMap.ts with:
  - slideBasePages: export page number (legacy NN/51 numbering) of click-state 0
  - slideClickCounts: number of click steps per logical slide
  - TOTAL_PAGES: 51

Also writes deck/data/pagemap.json (full detail: files per group, titles) and
prints a human-readable table.
"""
import json
import re
from pathlib import Path
from bs4 import BeautifulSoup

SLIDES_DIR = Path('/home/z/my-project/download/slides')
OUT_TS = Path(__file__).resolve().parent.parent / 'data' / 'pageMap.ts'
OUT_JSON = Path(__file__).resolve().parent.parent / 'data' / 'pagemap.json'


def visible_lines(html: str) -> list[str]:
    soup = BeautifulSoup(html, 'html.parser')
    for el in soup.find_all(['aside', 'script', 'style']):
        el.decompose()
    for el in soup.find_all(attrs={'data-decor': True}):
        el.decompose()
    # drop page badge (differs per file)
    for el in soup.select('.page-badge'):
        el.decompose()
    # drop hidden blocks
    for el in soup.find_all(style=re.compile(r'visibility\s*:\s*hidden')):
        el.decompose()
    lines = []
    for el in soup.find_all(['h1', 'h2', 'h3', 'h4', 'p', 'li', 'span', 'div', 'td', 'th', 'code', 'pre']):
        direct = ''.join(c for c in el.contents if isinstance(c, str))
        t = re.sub(r'\s+', ' ', direct).strip()
        if t and len(t) > 1:
            lines.append(t)
    return lines


def badge_num(html: str) -> int | None:
    m = re.search(r'badge-num">\s*(\d+)\s*/', html)
    return int(m.group(1)) if m else None


def main():
    files = sorted(SLIDES_DIR.glob('slide_*.html'))
    infos = []
    for f in files:
        html = f.read_text(encoding='utf-8')
        infos.append({
            'file': f.name,
            'badge': badge_num(html),
            'lines': visible_lines(html),
        })

    # group: consecutive files where current visible lines are a superset of prev's
    groups: list[list[dict]] = []
    for info in infos:
        if groups and set(info['lines']) >= set(groups[-1][0]['lines']) and len(info['lines']) > 0:
            # superset of the GROUP BASE -> same slide, more revealed
            groups[-1].append(info)
        else:
            groups.append([info])

    slide_base_pages = []
    slide_click_counts = []
    detail = []
    for g in groups:
        base = g[0]
        n_steps = len(g) - 1
        slide_base_pages.append(base['badge'])
        slide_click_counts.append(n_steps)
        detail.append({
            'base_page': base['badge'],
            'steps': n_steps,
            'files': [x['file'] for x in g],
        })

    total = slide_base_pages[-1] + slide_click_counts[-1]
    assert len(groups) == 33, f'expected 33 logical slides, got {len(groups)}'
    assert total == 51, f'expected 51 export pages, got {total}'
    assert slide_base_pages == sorted(slide_base_pages)

    ts = f'''// GENERATED by scripts/build_page_map.py - do not edit manually.
// Maps logical slides ({len(groups)}) onto legacy export page numbers (NN / {total}).
export const TOTAL_PAGES = {total}
export const slideBasePages: number[] = {json.dumps(slide_base_pages)}
export const slideClickCounts: number[] = {json.dumps(slide_click_counts)}
'''
    OUT_TS.write_text(ts, encoding='utf-8')
    OUT_JSON.write_text(json.dumps({'total': total, 'slides': detail}, ensure_ascii=False, indent=2), encoding='utf-8')

    print(f'Logical slides: {len(groups)}, click steps total: {sum(slide_click_counts)}, export pages: {total}')
    for d in detail:
        print(f"  page {d['base_page']:>2} +{d['steps']} clicks  <- {', '.join(d['files'])}")


if __name__ == '__main__':
    main()
