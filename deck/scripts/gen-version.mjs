// gen-version.mjs — writes deck/data/version.ts with `v<YYYYMMDD>.<short-sha>`.
// Date is Europe/Moscow (UTC+3). Run via `npm run gen:version` (wired as pre-hook).
import { execSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const repoRoot = new URL('../../', import.meta.url).pathname
const pad = (n) => String(n).padStart(2, '0')

let sha = 'nogit'
try {
  sha = execSync('git rev-parse --short HEAD', { cwd: repoRoot }).toString().trim()
} catch { /* not a git repo (should not happen) */ }

const msk = new Date(Date.now() + 3 * 3600 * 1000)
const date = `${msk.getUTCFullYear()}${pad(msk.getUTCMonth() + 1)}${pad(msk.getUTCDate())}`

const version = `v${date}.${sha}`
const out = `// GENERATED by scripts/gen-version.mjs — do not edit manually.
// date (Europe/Moscow) + short git SHA of the repo at build time
export const DECK_VERSION = '${version}'
`
writeFileSync(new URL('../data/version.ts', import.meta.url), out)
console.log('DECK_VERSION =', version)
